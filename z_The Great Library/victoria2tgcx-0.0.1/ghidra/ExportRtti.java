// Exports the RTTI classes the analysis found ("vftable" symbols inside each
// class's namespace) to a Markdown table: class, the vtable's VA and RVA, and
// the slot count. For the requested classes, also each slot with the function
// it points to.
//
// Headless use (on the already analysed project):
//   -process v2game.exe -noanalysis -postScript ExportRtti.java <output.md> [Class1,Class2,...]
//@category V2RE

import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.mem.Memory;
import ghidra.program.model.mem.MemoryBlock;
import ghidra.program.model.symbol.Symbol;
import ghidra.program.model.symbol.SymbolIterator;
import ghidra.program.model.symbol.SymbolTable;

public class ExportRtti extends GhidraScript {

	private static final long IMAGE_BASE = 0x400000L;
	private static final int MAX_SLOTS = 512;

	@Override
	protected void run() throws Exception {
		String[] args = getScriptArgs();
		String out = args.length > 0 ? args[0] : askString("Output", ".md file");
		Set<String> detail = new HashSet<>();
		// cmd.exe splits "A,B,C" into three arguments (P14): both forms are accepted.
		for (int i = 1; i < args.length; i++) {
			detail.addAll(Arrays.asList(args[i].split(",")));
		}

		SymbolTable st = currentProgram.getSymbolTable();
		List<String[]> rows = new ArrayList<>();
		List<String> details = new ArrayList<>();

		SymbolIterator it = st.getSymbols("vftable");
		while (it.hasNext() && !monitor.isCancelled()) {
			Symbol s = it.next();
			String cls = s.getParentNamespace().getName(true);
			Address a = s.getAddress();
			List<Address> slots = slots(a);
			rows.add(new String[] { cls, hex(a.getOffset()), hex(a.getOffset() - IMAGE_BASE),
				Integer.toString(slots.size()) });

			String simple = s.getParentNamespace().getName();
			if (detail.contains(simple) || detail.contains(cls)) {
				StringBuilder sb = new StringBuilder();
				sb.append("\n### ").append(cls).append(" — vtable ").append(hex(a.getOffset())).append("\n\n");
				sb.append("| slot | +off | function | VA |\n|---|---|---|---|\n");
				for (int i = 0; i < slots.size(); i++) {
					Address t = slots.get(i);
					Function f = getFunctionAt(t);
					sb.append(String.format("| %d | 0x%X | %s | %s |\n", i, i * 4,
						f != null ? f.getName() : "?", hex(t.getOffset())));
				}
				details.add(sb.toString());
			}
		}
		rows.sort((x, y) -> x[0].compareTo(y[0]));

		try (PrintWriter w = new PrintWriter(out, "UTF-8")) {
			w.println("# RTTI classes of v2game.exe (generated)");
			w.println();
			w.println("> Generated by `ghidra/ExportRtti.java` from `E:\\v2re\\ghidra\\v2game.gpr`. "
				+ "Do not edit by hand: it is regenerated. Slots = consecutive pointers to code "
				+ "up to the next symbol.");
			w.println();
			w.println(String.format("%d vtables.", rows.size()));
			w.println();
			w.println("| class | vtable VA | RVA | slots |");
			w.println("|---|---|---|---|");
			for (String[] r : rows) {
				w.println(String.format("| `%s` | %s | %s | %s |", r[0], r[1], r[2], r[3]));
			}
			if (!details.isEmpty()) {
				w.println();
				w.println("## Slots of the mechanics' classes");
				for (String d : details) {
					w.print(d);
				}
			}
		}
		println("ExportRtti: " + rows.size() + " vtables, " + details.size() + " with detail -> " + out);
	}

	private List<Address> slots(Address vt) throws Exception {
		Memory mem = currentProgram.getMemory();
		SymbolTable st = currentProgram.getSymbolTable();
		List<Address> res = new ArrayList<>();
		for (int i = 0; i < MAX_SLOTS; i++) {
			Address p = vt.add(4L * i);
			if (i > 0 && st.getPrimarySymbol(p) != null) {
				break;
			}
			long v = mem.getInt(p) & 0xFFFFFFFFL;
			Address t = toAddr(v);
			MemoryBlock b = mem.getBlock(t);
			if (b == null || !b.isExecute()) {
				break;
			}
			res.add(t);
		}
		return res;
	}

	private static String hex(long v) {
		return String.format("0x%08X", v);
	}
}
