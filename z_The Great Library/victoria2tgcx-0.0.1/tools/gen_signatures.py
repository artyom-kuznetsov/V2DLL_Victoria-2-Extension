"""Generate our DLL signature table from check_exe.py; never copy PE bytes."""

import argparse
import hashlib
import json
from pathlib import Path

import check_exe
from tgc_scan import parse, read
from tgcx_pe import PE

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "dll/tgcx/tgcx_signatures.h"
TGC = Path(r"E:\Victoria.II.v3.04.Inclu.ALL.DLC\mod\TGC_v2.5.2\TGC")


def generate(exe, tgc):
    image = PE(exe)
    if hashlib.sha256(image.data).hexdigest() != check_exe.SHA256:
        raise ValueError("reference executable hash mismatch")
    relocs = image.relocations()
    lines = ["// Generated by tools/gen_signatures.py from check_exe.SIGNATURES.",
             "#pragma once", "#include <stdint.h>",
             f'constexpr char tgcx_exe_sha256[] = "{check_exe.SHA256}";',
             f"constexpr uint32_t tgcx_preferred_base = 0x{image.base:X};",
             f"constexpr uint32_t tgcx_image_size = 0x{image.image_size:X};",
             "struct tgcx_Signature { uint32_t rva; unsigned char bytes[32];",
             "    unsigned int length; int reloc[8]; unsigned int reloc_count; const char* name; };",
             "constexpr tgcx_Signature tgcx_signatures[] = {"]
    for rva, expected, name in check_exe.SIGNATURES:
        data = bytes.fromhex(expected)
        if image.data[image.offset(rva):image.offset(rva) + len(data)] != data:
            raise ValueError(f"signature mismatch at {rva:#x}")
        offsets = [p - rva for p in relocs if rva - 3 <= p < rva + len(data)]
        if len(data) > 32 or len(offsets) > 8:
            raise ValueError("signature exceeds the C++ table capacity")
        if any(p < 0 or p + 4 > len(data) for p in offsets):
            raise ValueError(f"signature partially covers relocation at {rva:#x}")
        values = ", ".join(f"0x{b:02X}" for b in data)
        positions = ", ".join(map(str, offsets)) or "0"
        lines.append(f"    {{0x{rva:X}, {{{values}}}, {len(data)}, {{{positions}}}, {len(offsets)}, {json.dumps(name)}}},")
    lines += ["};", "// TGC names only: DLL-1 resolves every index/colour from the engine, never file order."]
    names = [name for _, group in parse(read(tgc / "common/ideologies.txt"))
             if isinstance(group, list) for name, body in group if isinstance(body, list)]
    if len(names) != 9 or len(set(names)) != 9:
        raise ValueError("expected the nine TGC v2.5.2 ideologies")
    lines += ["constexpr const char* tgcx_ideology_candidates[] = {",
              *[f"    {json.dumps(name)}," for name in names], "};", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--exe", type=Path, default=Path(check_exe.DEFAULT_EXE))
    ap.add_argument("--tgc", type=Path, default=TGC)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    content = generate(args.exe, args.tgc)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("gen_signatures: stale header; regenerate it")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"gen_signatures: ALL OK ({len(check_exe.SIGNATURES)} signatures, 9 ideology candidates)")


if __name__ == "__main__":
    main()
